def get_fallback_response(message: str) -> str:
    """
    Ищет наиболее релевантный fallback-ответ по ключевым словам в сообщении.
    """
    message_lower = message.lower()

    # Score each topic by keyword matches
    best_match = None
    best_score = 0

    for keyword, response in FALLBACK_RESPONSES.items():
        if keyword in message_lower:
            # Longer keyword match = more specific = higher priority
            score = len(keyword)
            if score > best_score:
                best_score = score
                best_match = response

    return best_match or DEFAULT_FALLBACK
