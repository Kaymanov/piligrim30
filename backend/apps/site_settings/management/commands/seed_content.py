ASSETS_DIR = Path(settings.BASE_DIR) / "seed_assets"


class Command(BaseCommand):
    help = "Заполняет БД демонстрационным контентом (услуги, статьи, кейсы, FAQ, отзывы, настройки)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--flush",
            action="store_true",
            help="Удалить существующий контент перед заполнением.",
        )
        parser.add_argument(
            "--no-images",
            action="store_true",
            help="Не прикреплять обложки (быстрее).",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        self.attach_images = not options["no_images"]

        if options["flush"]:
            self._flush()

        self.stdout.write(self.style.MIGRATE_HEADING("Заполнение контентом…"))
        self._seed_site_settings()
        self._seed_services()
        self._seed_blog()
        self._seed_cases()
        self._seed_faq()
        self._seed_reviews()
        self.stdout.write(self.style.SUCCESS("Готово! Контент загружен."))

    # ─── helpers ──────────────────────────────────────────────────────────

    def _flush(self):
        self.stdout.write(self.style.WARNING("Удаление существующего контента…"))
        Review.objects.all().delete()
        FAQ.objects.all().delete()
        Case.objects.all().delete()
        BlogPost.objects.all().delete()
        BlogCategory.objects.all().delete()
        Service.objects.all().delete()

    def _attach_image(self, instance, field_name, asset_relpath):
        """Attach an image from seed_assets if the field is empty and file exists."""
        if not self.attach_images:
            return
        field = getattr(instance, field_name)
        if field:  # already has an image
            return
        path = ASSETS_DIR / asset_relpath
        if not path.exists():
            self.stdout.write(
                self.style.WARNING(f"  ⚠ нет файла {asset_relpath}, пропуск обложки")
            )
            return
        with open(path, "rb") as f:
            getattr(instance, field_name).save(
                os.path.basename(asset_relpath), File(f), save=True
            )

    def _ok(self, label, obj, created):
        verb = "создано" if created else "обновлено"
        self.stdout.write(f"  • {label}: {obj} ({verb})")

